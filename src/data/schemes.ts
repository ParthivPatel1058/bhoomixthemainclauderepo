/**
 * Government scheme catalogue.
 *
 * Bundled rather than fetched: myScheme's API requires credentials (401 to the
 * public) and API Setu needs organisational registration, so there is no free
 * live endpoint to read from. This ships as data so the page works offline and
 * instantly, and `useSchemes` layers a Supabase table on top when one exists,
 * so schemes can be corrected without a redeploy.
 *
 * Figures verified August 2026. Anything time-sensitive (installment dates,
 * revised limits) is deliberately described qualitatively rather than pinned to
 * a number that will silently go stale.
 */

